import { decoders as d, detailsOf, isError, type ApiError, type Decoded } from "@/api";
import { formatCount } from "@/ui";

/**
 * U52 (ux; api 6af9e279d, domain 91b0cbbfc): a start drafts one UTC day; its template fan-out
 * counts toward a limit (gross: days that already exist count too), and each template stops at
 * its per-run cap. Words from the data, never a hard-coded limit (ux).
 */
export const startEstimateReader = d.object({
  count: d.integer,
  limit: d.integer,
  capped: d.optional(
    d.array(
      d.object({
        // free-text: the template's name, shown as is in the cap line.
        template: d.object({ id: d.token, name: d.string }),
        limit: d.integer,
        last_at: d.timestamp,
      }),
      500,
    ),
  ),
});
export type StartEstimate = Decoded<typeof startEstimateReader>;

const ADVICE = "Include fewer templates, or narrow their targets.";

/** The limit sentence, with whatever of count and limit is known. */
export function limitSentence(count: number | null, limit: number | null): string {
  if (count !== null && limit !== null)
    return `This start counts ${formatCount(count)} template requirements toward the limit of ${formatCount(limit)}, including days that already exist. ${ADVICE}`;
  return limit !== null
    ? `This start goes over the limit of ${formatCount(limit)} template requirements. ${ADVICE}`
    : `This start goes over the limit of template requirements. ${ADVICE}`;
}

/** Over the limit before anyone presses Start: the reason Start is disabled; null otherwise. */
export const overLimit = (e: StartEstimate | null): string | null =>
  e && e.count > e.limit ? limitSentence(e.count, e.limit) : null;

/** ux: 'Block 1 daily stops at 12:00Z: it reached its limit of 8 occurrences per run, so …'. */
export function capLines(e: StartEstimate | null): readonly string[] {
  return (e?.capped ?? []).map((c) => {
    const at = new Date(c.last_at).toISOString();
    return `${c.template.name} stops at ${at.slice(11, 16)}Z: it reached its limit of ${plural(c.limit)} per run, so its later occurrences on ${at.slice(5, 10)} aren't generated by this start.`;
  });
}
const plural = (n: number) => `${formatCount(n)} ${n === 1 ? "occurrence" : "occurrences"}`;

const limitDetails = d.object({ count: d.optional(d.integer), limit: d.optional(d.integer) });

/** Start's 422 (the backstop): the same sentence, or null for any other error. */
export function limitRefusal(error: ApiError | null): string | null {
  if (!error || !isError(error, "fleet_planning_occurrence_limit_exceeded")) return null;
  const det = detailsOf(error, limitDetails);
  return limitSentence(det?.count ?? null, det?.limit ?? null);
}
