import { describe, expect, it } from "vite-plus/test";
import { decode, type ApiError } from "@/api";
import {
  capLines,
  limitRefusal,
  limitSentence,
  overLimit,
  startEstimateReader,
} from "./start-limit.ts";

const estimate = (count: number, capped: unknown[] = []) => {
  const r = decode(startEstimateReader, { count, limit: 50_000, capped });
  if (!r.ok) throw r.error;
  return r.value;
};
const refusal = (
  details: unknown,
  code = "fleet_planning_occurrence_limit_exceeded",
): ApiError => ({
  kind: "invalid",
  code,
  message: "",
  details,
});

describe("U52 start limit (ux)", () => {
  it("counts toward the limit from the data, never a hard-coded one", () => {
    expect(limitSentence(62_400, 50_000)).toBe(
      "This start counts 62,400 template requirements toward the limit of 50,000, including days that already exist. Include fewer templates, or narrow their targets.",
    );
    expect(limitSentence(null, 40_000)).toBe(
      "This start goes over the limit of 40,000 template requirements. Include fewer templates, or narrow their targets.",
    );
    expect(limitSentence(null, null)).toBe(
      "This start goes over the limit of template requirements. Include fewer templates, or narrow their targets.",
    );
  });

  it("disables Start only over the limit; at or under it says nothing", () => {
    expect(overLimit(estimate(50_000))).toBeNull();
    expect(overLimit(null)).toBeNull();
    expect(overLimit(estimate(62_400))).toContain("counts 62,400");
  });

  it("names each capped template's stop time and day", () => {
    const e = estimate(120, [
      { template: { id: "t1", name: "Block 1 daily" }, limit: 8, last_at: "2026-11-20T12:00:00Z" },
    ]);
    expect(capLines(e)).toEqual([
      "Block 1 daily stops at 12:00Z: it reached its limit of 8 occurrences per run, so its later occurrences on 11-20 aren't generated by this start.",
    ]);
    expect(capLines(estimate(1))).toEqual([]);
  });

  it("reads Start's 422 with or without details; other errors aren't it", () => {
    expect(limitRefusal(refusal({ count: 62_400, limit: 50_000 }))).toContain("counts 62,400");
    expect(limitRefusal(refusal(null))).toContain("goes over the limit of template");
    expect(limitRefusal(refusal(null, "planning_not_set_up"))).toBeNull();
    expect(limitRefusal(null)).toBeNull();
  });
});
