defmodule Cadence.ContactPlanning.RequirementListing do
  @moduledoc """
  A bounded page of a mission's contact requirements at their current version, most recently
  changed first (console requirement list, BACKLOG §8 8g). Filters: `spacecraft_id`, `state`
  (`active | closed | canceled`) and `source` (`one_off`: declared directly; `template`:
  generated by a recurring template). Callers authorize first.
  """

  import Ecto.Query

  alias Cadence.ContactPlanning.{ContactRequirement, ContactRequirementVersion}

  alias Cadence.Management.Contacts.Store.{
    ContactRequirementRow,
    ContactRequirementVersionRow
  }

  alias Cadence.Repo

  @type filters :: %{
          optional(:spacecraft_id) => binary() | nil,
          optional(:state) => :active | :closed | :canceled | nil,
          optional(:source) => :one_off | :template | nil,
          page: pos_integer(),
          limit: pos_integer()
        }

  @spec page(binary(), binary(), filters()) :: %{
          entries: [{ContactRequirement.t(), ContactRequirementVersion.t()}],
          next_page: pos_integer() | nil
        }
  def page(organization_id, mission_id, %{page: page, limit: limit} = filters)
      when is_binary(organization_id) and is_binary(mission_id) and page > 0 and limit > 0 do
    rows =
      ContactRequirementRow
      |> join(:inner, [requirement], version in ContactRequirementVersionRow,
        on:
          version.organization_id == requirement.organization_id and
            version.mission_id == requirement.mission_id and
            version.contact_requirement_id == requirement.contact_requirement_id and
            version.version == requirement.current_version
      )
      |> where(
        [requirement],
        requirement.organization_id == ^organization_id and requirement.mission_id == ^mission_id
      )
      |> spacecraft(filters[:spacecraft_id])
      |> state(filters[:state])
      |> source(filters[:source])
      |> order_by([requirement, version],
        desc: version.created_at,
        asc: requirement.contact_requirement_id
      )
      |> offset(^((page - 1) * limit))
      |> limit(^(limit + 1))
      |> select([requirement, version], {requirement, version})
      |> Repo.all()

    %{
      entries:
        rows
        |> Enum.take(limit)
        |> Enum.map(fn {requirement, version} ->
          {ContactRequirementRow.to_domain(requirement),
           ContactRequirementVersionRow.to_domain(version)}
        end),
      next_page: if(length(rows) > limit, do: page + 1)
    }
  end

  @doc """
  Template-generated requirements whose window opens in `[from, to)`, counted per template:
  `%{template_id => %{count, active_count}}` (current versions, any state; `active_count` the
  active ones). One grouped query.
  """
  @spec counts_by_template(binary(), binary(), DateTime.t(), DateTime.t()) :: %{
          binary() => %{count: non_neg_integer(), active_count: non_neg_integer()}
        }
  def counts_by_template(organization_id, mission_id, %DateTime{} = from, %DateTime{} = to) do
    ContactRequirementRow
    |> join(:inner, [requirement], version in ContactRequirementVersionRow,
      on:
        version.organization_id == requirement.organization_id and
          version.mission_id == requirement.mission_id and
          version.contact_requirement_id == requirement.contact_requirement_id and
          version.version == requirement.current_version
    )
    |> where(
      [requirement, version],
      requirement.organization_id == ^organization_id and requirement.mission_id == ^mission_id and
        version.earliest_start >= ^from and version.earliest_start < ^to
    )
    |> source(:template)
    |> group_by(
      [_requirement, version],
      fragment("?->'value'->'generation'->>'contact_requirement_template_id'", version.metadata)
    )
    |> select([requirement, version], {
      fragment("?->'value'->'generation'->>'contact_requirement_template_id'", version.metadata),
      count(requirement.contact_requirement_id),
      filter(count(requirement.contact_requirement_id), requirement.lifecycle_state == "active")
    })
    |> Repo.all()
    |> Map.new(fn {id, count, active} -> {id, %{count: count, active_count: active}} end)
  end

  @doc "The template that generated `version`, or nil for a one-off requirement."
  @spec template_id(ContactRequirementVersion.t()) :: binary() | nil
  def template_id(%{metadata: %{"generation" => %{"contact_requirement_template_id" => id}}}),
    do: id

  def template_id(_version), do: nil

  @doc "The template version that generated `version` (U48 Source \"· v2\"), or nil for a one-off."
  @spec template_version(ContactRequirementVersion.t()) :: pos_integer() | nil
  def template_version(%{
        metadata: %{"generation" => %{"contact_requirement_template_version" => v}}
      })
      when is_integer(v),
      do: v

  def template_version(_version), do: nil

  defp spacecraft(query, nil), do: query

  defp spacecraft(query, id),
    do: where(query, [_requirement, version], version.spacecraft_id == ^id)

  defp state(query, nil), do: query

  defp state(query, state) when state in [:active, :closed, :canceled],
    do: where(query, [requirement], requirement.lifecycle_state == ^Atom.to_string(state))

  # Template-generated versions carry `generation` metadata (stored wrapped under `value`).
  defp source(query, nil), do: query

  defp source(query, :template),
    do:
      where(
        query,
        [_requirement, version],
        fragment("(?->'value'->'generation') IS NOT NULL", version.metadata)
      )

  defp source(query, :one_off),
    do:
      where(
        query,
        [_requirement, version],
        fragment("(?->'value'->'generation') IS NULL", version.metadata)
      )
end
