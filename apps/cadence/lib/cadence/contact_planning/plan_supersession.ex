defmodule Cadence.ContactPlanning.PlanSupersession do
  @moduledoc """
  Whether newer requirement or template versions have overtaken a draft (K1,
  ux ScheduleFlow `superseded`). A plan that is still `draft` or
  `pending_approval` is superseded when a requirement it was planned for:

  - was generated by a template that has a newer version since, or no longer
    targets its spacecraft, whether or not supersession has cancelled it yet
    (`template_changed`; U27: the read is truthful as soon as the template is
    bumped, not only when the next draft starts);
  - was cancelled or closed otherwise (`requirement_closed`);
  - has a newer version than the plan used (`requirement_changed`).

  Returns `%{at, by: %{name} | nil, reason, changes: [%{kind, id, name,
  from_version, to_version}]}` or nil. Nothing is written: the plan keeps its
  state, the console shows it dimmed with why.
  """

  alias Cadence.Accounts

  alias Cadence.ContactPlanning.{
    ContactPlans,
    ContactRequirements,
    ContactRequirementTemplates,
    TemplateSupersession,
    TemplateTargets
  }

  @open [:draft, :pending_approval]

  @spec check(binary(), binary(), map(), map()) :: map() | nil
  def check(organization_id, mission_id, plan, version),
    do:
      organization_id
      |> check_many(mission_id, [{plan, version}])
      |> Map.get(plan.contact_plan_id)

  @doc """
  `check/4` for many plans at once (list reads; domain re-review F): requirements, plan uptake
  and templates are each read once for the whole batch. `%{plan_id => superseded | nil}`.
  """
  @spec check_many(binary(), binary(), [{map(), map()}]) :: %{binary() => map() | nil}
  def check_many(organization_id, mission_id, pairs) do
    open = Enum.filter(pairs, fn {plan, _version} -> plan.lifecycle_state in @open end)
    refs = Map.new(open, fn {plan, version} -> {plan.contact_plan_id, refs(version)} end)
    ids = refs |> Map.values() |> List.flatten() |> Enum.map(&elem(&1, 0)) |> Enum.uniq()
    requirements = ContactRequirements.fetch_many(organization_id, mission_id, ids)

    context = %{
      templates: templates(organization_id, mission_id, Map.values(requirements)),
      uptake: ContactPlans.requirement_uptake(organization_id, mission_id, ids),
      now: DateTime.utc_now()
    }

    Map.new(pairs, fn {plan, _version} ->
      superseded =
        if plan.lifecycle_state in @open,
          do:
            plan
            |> plan_changes(Map.get(refs, plan.contact_plan_id, []), requirements, context)
            |> summarize()

      {plan.contact_plan_id, superseded}
    end)
  end

  defp plan_changes(plan, refs, requirements, context) do
    Enum.flat_map(refs, fn {id, used} ->
      case Map.get(requirements, id) do
        {requirement, current} ->
          requirement_change(requirement, current, used, kept?(plan, id, context), context)

        nil ->
          []
      end
    end)
  end

  @doc """
  Dry run for a save (ux ContactPlanning.md): the open drafts a new version of the template or
  requirement would supersede, by the same rule as `check/4`. A new template version supersedes
  drafts holding its future, untaken requirements; a new requirement version supersedes every
  draft that references it. Booked or pending plans aren't drafts (they're K2's). Writes nothing.
  """
  @spec would_supersede(binary(), binary(), {:template | :requirement, binary()}) :: [
          {map(), map()}
        ]
  def would_supersede(organization_id, mission_id, subject) do
    drafts = ContactPlans.list(organization_id, mission_id, lifecycle_state: :draft)
    refs = Map.new(drafts, fn {plan, version} -> {plan.contact_plan_id, refs(version)} end)
    ids = refs |> Map.values() |> List.flatten() |> Enum.map(&elem(&1, 0)) |> Enum.uniq()
    requirements = ContactRequirements.fetch_many(organization_id, mission_id, ids)

    context = %{
      uptake: ContactPlans.requirement_uptake(organization_id, mission_id, ids),
      now: DateTime.utc_now()
    }

    Enum.filter(drafts, fn {plan, _version} ->
      refs
      |> Map.get(plan.contact_plan_id, [])
      |> Enum.any?(fn {id, _used} ->
        affected?(subject, id, Map.get(requirements, id), plan, context)
      end)
    end)
  end

  defp affected?({:requirement, requirement_id}, id, _requirement, _plan, _context),
    do: id == requirement_id

  defp affected?({:template, template_id}, id, {requirement, current}, plan, context) do
    requirement.lifecycle_state == :active and
      generation(current)["contact_requirement_template_id"] == template_id and
      DateTime.after?(current.earliest_start, context.now) and not kept?(plan, id, context)
  end

  defp affected?(_subject, _id, nil, _plan, _context), do: false

  defp refs(version) do
    for %{"id" => id, "version" => used} <-
          (version.requirement_refs_document || %{})["requirements"] || [],
        do: {id, used}
  end

  # Supersession keeps requirements a plan in pending_approval or later took up: another plan's
  # (a booked source plan's, which a repair re-plans), or this plan's own once it's submitted
  # (re-review G3). A draft doesn't keep its own.
  defp kept?(plan, requirement_id, context) do
    takers = Map.get(context.uptake, requirement_id, [])

    if plan.lifecycle_state == :draft,
      do: Enum.any?(takers, &(&1 != plan.contact_plan_id)),
      else: takers != []
  end

  # Each generating template once: its current version, whether it's active, who it targets now.
  defp templates(organization_id, mission_id, requirements) do
    requirements
    |> Enum.map(fn {_r, current} -> generation(current)["contact_requirement_template_id"] end)
    |> Enum.reject(&is_nil/1)
    |> Enum.uniq()
    |> Map.new(fn template_id ->
      case ContactRequirementTemplates.fetch(organization_id, mission_id, template_id) do
        {:ok, template, version} ->
          targets = TemplateTargets.resolve(organization_id, mission_id, version.target_document)
          {template_id, {version, MapSet.new(targets), template.lifecycle_state == :active}}

        _missing ->
          {template_id, nil}
      end
    end)
  end

  defp generation(current), do: (current.metadata || %{})["generation"] || %{}

  defp requirement_change(requirement, current, used, kept?, context) do
    reason = requirement.lifecycle_reason || ""
    template = Map.get(context.templates, generation(current)["contact_requirement_template_id"])

    cond do
      requirement.lifecycle_state == :canceled and template_cause?(reason) ->
        [
          template_change(
            requirement.lifecycle_changed_at,
            requirement.lifecycle_changed_by,
            current,
            template
          )
        ]

      stale_template?(requirement, current, template, kept?, context.now) ->
        {version, _targets, _active?} = template
        [template_change(version.created_at, version.created_by, current, template)]

      requirement.lifecycle_state in [:canceled, :closed] ->
        [
          %{
            reason: "requirement_closed",
            at: requirement.lifecycle_changed_at,
            by: requirement.lifecycle_changed_by,
            change: requirement_ref(requirement, current, used)
          }
        ]

      requirement.current_version > used ->
        [
          %{
            reason: "requirement_changed",
            at: current.created_at,
            by: current.created_by,
            change: requirement_ref(requirement, current, used)
          }
        ]

      true ->
        []
    end
  end

  # The same rule supersession applies (re-review C): only a future requirement of an active
  # template, not taken up, from an older version or for a spacecraft no longer targeted.
  defp stale_template?(%{lifecycle_state: :active}, current, {version, targets, true}, false, now) do
    DateTime.after?(current.earliest_start, now) and
      current
      |> generation()
      |> Map.put("spacecraft_id", current.spacecraft_id)
      |> TemplateSupersession.cause(version, targets)
      |> Kernel.!=(nil)
  end

  defp stale_template?(_requirement, _current, _template, _kept?, _now), do: false

  defp template_change(at, by, current, template) do
    generation = generation(current)

    {name, to_version} =
      case template do
        {version, _targets, _active?} -> {version.name, version.version}
        nil -> {nil, nil}
      end

    %{
      reason: "template_changed",
      at: at,
      by: by,
      change: %{
        kind: "template",
        id: generation["contact_requirement_template_id"],
        name: name,
        from_version: generation["contact_requirement_template_version"],
        to_version: to_version
      }
    }
  end

  defp requirement_ref(requirement, current, used),
    do: %{
      kind: "requirement",
      id: requirement.contact_requirement_id,
      name: current.contact_intent,
      from_version: used,
      to_version: requirement.current_version
    }

  defp template_cause?(reason),
    do:
      String.starts_with?(reason, "template_versioned") or
        String.starts_with?(reason, "left_template_target")

  defp summarize([]), do: nil

  defp summarize(changes) do
    latest = Enum.max_by(changes, & &1.at, DateTime)

    reason =
      Enum.find_value(
        ["template_changed", "requirement_changed", "requirement_closed"],
        fn reason -> Enum.find_value(changes, &(&1.reason == reason and reason)) end
      )

    %{
      at: latest.at,
      by: actor(latest.by),
      reason: reason,
      changes: changes |> Enum.map(& &1.change) |> Enum.uniq()
    }
  end

  defp actor(user_id) when is_binary(user_id) do
    case Accounts.fetch_user(user_id) do
      {:ok, user} -> %{name: user.display_name || user.email}
      _system -> nil
    end
  end

  defp actor(_none), do: nil
end
