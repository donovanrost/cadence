defmodule Cadence.ContactPlanning.PlanSupersession do
  @moduledoc """
  Whether newer requirement or template versions have overtaken a draft (K1,
  ux ScheduleFlow `superseded`). A plan that is still `draft` or
  `pending_approval` is superseded when a requirement it was planned for:

  - was generated by a template that has a newer version since, or no longer
    targets its spacecraft, whether or not supersession has cancelled it yet
    (`template_changed`; U27: the read is truthful as soon as the template is
    bumped, not only when the next draft starts);
  - was cancelled or closed otherwise (`requirement_closed`);
  - has a newer version than the plan used (`requirement_changed`).

  Returns `%{at, by: %{name} | nil, reason, changes: [%{kind, id, name,
  from_version, to_version}]}` or nil. Nothing is written: the plan keeps its
  state, the console shows it dimmed with why.
  """

  alias Cadence.Accounts

  alias Cadence.ContactPlanning.{
    ContactPlans,
    ContactRequirements,
    ContactRequirementTemplates,
    TemplateSupersession,
    TemplateTargets
  }

  @open [:draft, :pending_approval]

  @spec check(binary(), binary(), map(), map()) :: map() | nil
  def check(organization_id, mission_id, %{lifecycle_state: state} = plan, version)
      when state in @open do
    requirements =
      ((version.requirement_refs_document || %{})["requirements"] || [])
      |> Enum.flat_map(&fetch(organization_id, mission_id, &1))

    templates = templates(organization_id, mission_id, requirements)

    # Supersession keeps requirements another plan has taken up (a booked source plan's, which
    # a repair re-plans), so they aren't stale here either.
    kept =
      ContactPlans.requirements_taken_up(
        organization_id,
        mission_id,
        Enum.map(requirements, fn {requirement, _, _} -> requirement.contact_requirement_id end),
        except_plan_id: plan.contact_plan_id
      )

    requirements
    |> Enum.flat_map(fn {requirement, current, used} ->
      requirement_change(requirement, current, used, templates, kept)
    end)
    |> summarize()
  end

  def check(_organization_id, _mission_id, _plan, _version), do: nil

  defp fetch(organization_id, mission_id, %{"id" => id, "version" => used}) do
    case ContactRequirements.fetch(organization_id, mission_id, id) do
      {:ok, requirement, current} -> [{requirement, current, used}]
      _missing -> []
    end
  end

  defp fetch(_organization_id, _mission_id, _ref), do: []

  # Each generating template once: its current version and who it targets now.
  defp templates(organization_id, mission_id, requirements) do
    requirements
    |> Enum.map(fn {_r, current, _used} ->
      generation(current)["contact_requirement_template_id"]
    end)
    |> Enum.reject(&is_nil/1)
    |> Enum.uniq()
    |> Map.new(fn template_id ->
      case ContactRequirementTemplates.fetch(organization_id, mission_id, template_id) do
        {:ok, _template, version} ->
          targets = TemplateTargets.resolve(organization_id, mission_id, version.target_document)
          {template_id, {version, MapSet.new(targets)}}

        _missing ->
          {template_id, nil}
      end
    end)
  end

  defp generation(current), do: (current.metadata || %{})["generation"] || %{}

  defp requirement_change(requirement, current, used, templates, kept) do
    reason = requirement.lifecycle_reason || ""
    template = Map.get(templates, generation(current)["contact_requirement_template_id"])

    cond do
      requirement.lifecycle_state == :canceled and template_cause?(reason) ->
        [
          template_change(
            requirement.lifecycle_changed_at,
            requirement.lifecycle_changed_by,
            current,
            template
          )
        ]

      requirement.lifecycle_state == :active and
        not MapSet.member?(kept, requirement.contact_requirement_id) and
          overtaken?(current, template) ->
        {version, _targets} = template
        [template_change(version.created_at, version.created_by, current, template)]

      requirement.lifecycle_state in [:canceled, :closed] ->
        [
          %{
            reason: "requirement_closed",
            at: requirement.lifecycle_changed_at,
            by: requirement.lifecycle_changed_by,
            change: requirement_ref(requirement, current, used)
          }
        ]

      requirement.current_version > used ->
        [
          %{
            reason: "requirement_changed",
            at: current.created_at,
            by: current.created_by,
            change: requirement_ref(requirement, current, used)
          }
        ]

      true ->
        []
    end
  end

  defp overtaken?(_current, nil), do: false

  defp overtaken?(current, {version, targets}) do
    current
    |> generation()
    |> Map.put("spacecraft_id", current.spacecraft_id)
    |> TemplateSupersession.cause(version, targets)
    |> Kernel.!=(nil)
  end

  defp template_change(at, by, current, template) do
    generation = generation(current)

    {name, to_version} =
      case template do
        {version, _targets} -> {version.name, version.version}
        nil -> {nil, nil}
      end

    %{
      reason: "template_changed",
      at: at,
      by: by,
      change: %{
        kind: "template",
        id: generation["contact_requirement_template_id"],
        name: name,
        from_version: generation["contact_requirement_template_version"],
        to_version: to_version
      }
    }
  end

  defp requirement_ref(requirement, current, used),
    do: %{
      kind: "requirement",
      id: requirement.contact_requirement_id,
      name: current.contact_intent,
      from_version: used,
      to_version: requirement.current_version
    }

  defp template_cause?(reason),
    do:
      String.starts_with?(reason, "template_versioned") or
        String.starts_with?(reason, "left_template_target")

  defp summarize([]), do: nil

  defp summarize(changes) do
    latest = Enum.max_by(changes, & &1.at, DateTime)

    reason =
      Enum.find_value(
        ["template_changed", "requirement_changed", "requirement_closed"],
        fn reason -> Enum.find_value(changes, &(&1.reason == reason and reason)) end
      )

    %{
      at: latest.at,
      by: actor(latest.by),
      reason: reason,
      changes: changes |> Enum.map(& &1.change) |> Enum.uniq()
    }
  end

  defp actor(user_id) when is_binary(user_id) do
    case Accounts.fetch_user(user_id) do
      {:ok, user} -> %{name: user.display_name || user.email}
      _system -> nil
    end
  end

  defp actor(_none), do: nil
end
