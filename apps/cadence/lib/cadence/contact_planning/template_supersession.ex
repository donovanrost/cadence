defmodule Cadence.ContactPlanning.TemplateSupersession do
  @moduledoc """
  After a template version materializes, cancels the requirements it generated
  earlier that no longer apply (docs/apogee/domain/contact-templates.md):

  - `template_versioned`: generated by an older version of the template;
  - `left_template_target`: generated for a spacecraft the template no longer
    targets (it left the profile, or is now excluded).

  Only future requirements (not started yet) that no plan past draft has taken
  up are canceled. Anything already planned stays, and is left to the plan.
  """

  require Logger

  alias Cadence.Auth.Scope

  alias Cadence.ContactPlanning.{
    ContactPlans,
    ContactRequirements,
    ContactRequirementTemplateVersion
  }

  alias Cadence.Repo

  @doc """
  Cancels the stale generated requirements of `version`'s template (call it
  after `version` has materialized). Each cancel locks the requirement, then
  re-checks plan uptake `FOR SHARE`, so a requirement a plan took up in the
  meantime is kept.
  """
  @spec supersede(Scope.t(), ContactRequirementTemplateVersion.t(), [binary()], DateTime.t()) ::
          %{superseded: non_neg_integer()}
  def supersede(%Scope{} = scope, %ContactRequirementTemplateVersion{} = version, targets, now) do
    superseded =
      version.organization_id
      |> ContactRequirements.list_generated(
        version.mission_id,
        version.contact_requirement_template_id,
        now
      )
      |> stale(version, MapSet.new(targets))
      |> Enum.count(&cancel_unless_taken_up(scope, version, &1, now))

    %{superseded: superseded}
  end

  @doc """
  Pure: which of `requirements` (`[{requirement, current_version}]`, already
  generated by this template and in the future) would be superseded, with
  the cause: `[{requirement_id, cause}]`.
  """
  @spec stale([{map(), map()}], ContactRequirementTemplateVersion.t(), MapSet.t()) :: [
          {binary(), atom()}
        ]
  def stale(requirements, version, targets) do
    Enum.flat_map(requirements, fn {requirement, current} ->
      generation =
        ((current.metadata || %{})["generation"] || %{})
        |> Map.put("spacecraft_id", current.spacecraft_id)

      case cause(generation, version, targets) do
        nil -> []
        cause -> [{requirement.contact_requirement_id, cause}]
      end
    end)
  end

  @doc "Pure: the cause a generated requirement is superseded with, or nil."
  @spec cause(map(), ContactRequirementTemplateVersion.t(), MapSet.t()) ::
          :template_versioned | :left_template_target | nil
  def cause(generation, version, targets) do
    cond do
      generation["contact_requirement_template_id"] != version.contact_requirement_template_id ->
        nil

      (generation["contact_requirement_template_version"] || 0) < version.version ->
        :template_versioned

      not MapSet.member?(targets, generation["spacecraft_id"]) ->
        :left_template_target

      true ->
        nil
    end
  end

  defp cancel_unless_taken_up(scope, version, {requirement_id, cause}, now) do
    org = version.organization_id
    mission = version.mission_id

    reason =
      "#{cause}: superseded by template #{version.contact_requirement_template_id} " <>
        "version #{version.version}"

    Repo.transaction(fn ->
      with {:ok, %{lifecycle_state: :active} = requirement} <-
             ContactRequirements.lock(org, mission, requirement_id),
           false <-
             org
             |> ContactPlans.requirements_taken_up(mission, [requirement_id], lock: true)
             |> MapSet.member?(requirement_id),
           {:ok, _canceled} <-
             ContactRequirements.cancel(
               scope,
               mission,
               requirement_id,
               requirement.current_version,
               reason,
               now: now
             ) do
        true
      else
        _kept -> false
      end
    end)
    |> case do
      {:ok, superseded?} ->
        superseded?

      {:error, error} ->
        Logger.warning("could not supersede requirement #{requirement_id}: #{inspect(error)}")
        false
    end
  end
end
