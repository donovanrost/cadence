defmodule Cadence.ContactPlanning.TemplateSupersession do
  @moduledoc """
  After a template version materializes, cancels the requirements it generated
  earlier that no longer apply (docs/apogee/domain/contact-templates.md):

  - `template_versioned`: generated by an older version of the template;
  - `left_template_target`: generated for a spacecraft the template no longer
    targets (it left the profile, or is now excluded).

  Only future requirements (not started yet) that no plan past draft has taken
  up are canceled. Anything already planned stays, and is left to the plan.
  """

  import Ecto.Query

  require Logger

  alias Cadence.Auth.Scope
  alias Cadence.ContactPlanning.{ContactRequirements, ContactRequirementTemplateVersion}
  alias Cadence.Management.Contacts.Store.{ContactPlanRequirementRefRow, ContactPlanRow}
  alias Cadence.Repo

  @planned ~w(pending_approval approved executing partially_reserved reserved)

  @spec supersede(Scope.t(), ContactRequirementTemplateVersion.t(), [binary()], DateTime.t()) ::
          %{superseded: non_neg_integer()}
  def supersede(%Scope{} = scope, %ContactRequirementTemplateVersion{} = version, targets, now) do
    candidates = stale(version, MapSet.new(targets), now)
    planned = planned(version, Enum.map(candidates, fn {requirement, _, _} -> requirement end))

    superseded =
      candidates
      |> Enum.reject(fn {requirement, _, _} -> MapSet.member?(planned, requirement) end)
      |> Enum.count(&cancel(scope, version, &1, now))

    %{superseded: superseded}
  end

  @doc "Pure: the cause a generated requirement is superseded with, or nil."
  @spec cause(map(), ContactRequirementTemplateVersion.t(), MapSet.t()) ::
          :template_versioned | :left_template_target | nil
  def cause(generation, version, targets) do
    cond do
      generation["contact_requirement_template_id"] != version.contact_requirement_template_id ->
        nil

      (generation["contact_requirement_template_version"] || 0) < version.version ->
        :template_versioned

      not MapSet.member?(targets, generation["spacecraft_id"]) ->
        :left_template_target

      true ->
        nil
    end
  end

  defp stale(version, targets, now) do
    version.organization_id
    |> ContactRequirements.list(version.mission_id, lifecycle_state: :active)
    |> Enum.filter(fn {_requirement, current} -> DateTime.after?(current.earliest_start, now) end)
    |> Enum.flat_map(fn {requirement, current} ->
      generation =
        ((current.metadata || %{})["generation"] || %{})
        |> Map.put("spacecraft_id", current.spacecraft_id)

      case cause(generation, version, targets) do
        nil -> []
        cause -> [{requirement.contact_requirement_id, current.version, cause}]
      end
    end)
  end

  defp planned(_version, []), do: MapSet.new()

  defp planned(version, requirement_ids) do
    ContactPlanRequirementRefRow
    |> join(:inner, [ref], plan in ContactPlanRow,
      on:
        plan.organization_id == ref.organization_id and plan.mission_id == ref.mission_id and
          plan.contact_plan_id == ref.contact_plan_id
    )
    |> where(
      [ref, plan],
      ref.organization_id == ^version.organization_id and ref.mission_id == ^version.mission_id and
        ref.contact_requirement_id in ^requirement_ids and plan.lifecycle_state in ^@planned
    )
    |> distinct(true)
    |> select([ref], ref.contact_requirement_id)
    |> Repo.all()
    |> MapSet.new()
  end

  defp cancel(scope, version, {requirement_id, requirement_version, cause}, now) do
    reason =
      "#{cause}: superseded by template #{version.contact_requirement_template_id} " <>
        "version #{version.version}"

    case ContactRequirements.cancel(
           scope,
           version.mission_id,
           requirement_id,
           requirement_version,
           reason,
           now: now
         ) do
      {:ok, _requirement} ->
        true

      {:error, error} ->
        Logger.warning(
          "could not supersede requirement #{requirement_id} (#{cause}): #{inspect(error)}"
        )

        false
    end
  end
end
