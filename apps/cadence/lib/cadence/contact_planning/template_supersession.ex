defmodule Cadence.ContactPlanning.TemplateSupersession do
  @moduledoc """
  After a template version materializes, cancels the requirements it generated
  earlier that no longer apply (docs/apogee/domain/contact-templates.md):

  - `template_versioned`: generated by an older version of the template;
  - `left_template_target`: generated for a spacecraft the template no longer
    targets (it left the profile, or is now excluded).

  Only future requirements (not started yet) that no plan past draft has taken
  up are canceled. Anything already planned stays, and is left to the plan.
  """

  require Logger

  alias Cadence.Auth.Scope

  alias Cadence.ContactPlanning.{
    ContactPlans,
    ContactRequirements,
    ContactRequirementTemplateVersion
  }

  alias Cadence.Repo

  @doc """
  Cancels the stale generated requirements of `version`'s template whose
  occurrence is one of `occurrences`: exactly the occurrences `version` just
  materialized, so each cancelled slot has its replacement (review E; qa #86: a
  run whose lookback or per-run cap generated less than its range cancelled days
  it didn't replace). A `{from, until}` window is still accepted. Call it after
  `version` has materialized. For each requirement the referencing plans are
  share-locked first and uptake re-checked, then the requirement is locked and
  cancelled (plans before requirements; review A, B).
  """
  @spec supersede(
          Scope.t(),
          ContactRequirementTemplateVersion.t(),
          [binary()],
          DateTime.t(),
          [DateTime.t()] | {DateTime.t(), DateTime.t()}
        ) :: %{superseded: non_neg_integer()}
  def supersede(
        %Scope{} = scope,
        %ContactRequirementTemplateVersion{} = version,
        targets,
        now,
        slots
      ) do
    candidates =
      version.organization_id
      |> ContactRequirements.list_generated(
        version.mission_id,
        [version.contact_requirement_template_id],
        now
      )
      |> in_slots(slots)
      |> stale_versions(version, MapSet.new(targets))

    %{superseded: Enum.count(candidates, &cancel_unless_taken_up(scope, version, &1, now))}
  end

  @doc "Collects a reviewed fleet start's stale candidates before it inserts replacements."
  def prepare(organization_id, mission_id, templates, now) do
    template_ids = Enum.map(templates, & &1.version.contact_requirement_template_id)

    by_template =
      organization_id
      |> ContactRequirements.list_generated(mission_id, template_ids, now)
      |> Enum.group_by(fn {_requirement, current} ->
        get_in(current.metadata, ["generation", "contact_requirement_template_id"])
      end)

    Enum.map(templates, fn template ->
      candidates =
        by_template
        |> Map.get(template.version.contact_requirement_template_id, [])
        |> at_occurrences(template.occurrences)
        |> stale_versions(template.version, MapSet.new(template.spacecraft_ids))

      {template.version, candidates}
    end)
  end

  @doc "Cancels prepared candidates in the fleet start transaction after their replacements exist."
  def cancel_prepared(scope, mission_id, prepared, now) do
    cancellations =
      for {version, candidates} <- prepared, {id, current_version, cause} <- candidates do
        %{id: id, version: current_version, reason: supersession_reason(version, cause)}
      end

    taken_up =
      ContactPlans.requirements_taken_up(
        scope.organization_id,
        mission_id,
        Enum.map(cancellations, & &1.id),
        lock: true
      )

    cancellations = Enum.reject(cancellations, &MapSet.member?(taken_up, &1.id))
    ContactRequirements.cancel_superseded(scope, mission_id, cancellations, now)
  end

  defp in_slots(requirements, {%DateTime{}, %DateTime{}} = window),
    do: in_window(requirements, window)

  defp in_slots(requirements, occurrences) when is_list(occurrences),
    do: at_occurrences(requirements, occurrences)

  @doc "Requirements whose generating occurrence falls in `{from, until}` (inclusive)."
  @spec in_window([{map(), map()}], {DateTime.t(), DateTime.t()}) :: [{map(), map()}]
  def in_window(requirements, {from, until}) do
    Enum.filter(requirements, fn {_requirement, current} ->
      case generated_at(current) do
        {:ok, at} -> not DateTime.before?(at, from) and not DateTime.after?(at, until)
        :error -> false
      end
    end)
  end

  @doc "Requirements generated for one of `occurrences` (the occurrences a run generated)."
  @spec at_occurrences([{map(), map()}], [DateTime.t()]) :: [{map(), map()}]
  def at_occurrences(requirements, occurrences) do
    wanted = MapSet.new(occurrences, &DateTime.to_unix(&1, :microsecond))

    Enum.filter(requirements, fn {_requirement, current} ->
      case generated_at(current) do
        {:ok, at} -> MapSet.member?(wanted, DateTime.to_unix(at, :microsecond))
        :error -> false
      end
    end)
  end

  defp generated_at(current) do
    with at when is_binary(at) <- get_in(current.metadata || %{}, ["generation", "occurrence_at"]),
         {:ok, at, _offset} <- DateTime.from_iso8601(at) do
      {:ok, at}
    else
      _not_generated -> :error
    end
  end

  @doc """
  Pure: which of `requirements` (`[{requirement, current_version}]`, already
  generated by this template and in the future) would be superseded, with
  the cause: `[{requirement_id, cause}]`.
  """
  @spec stale([{map(), map()}], ContactRequirementTemplateVersion.t(), MapSet.t()) :: [
          {binary(), atom()}
        ]
  def stale(requirements, version, targets) do
    requirements
    |> stale_versions(version, targets)
    |> Enum.map(fn {id, _current_version, cause} -> {id, cause} end)
  end

  defp stale_versions(requirements, version, targets) do
    Enum.flat_map(requirements, fn {requirement, current} ->
      generation =
        ((current.metadata || %{})["generation"] || %{})
        |> Map.put("spacecraft_id", current.spacecraft_id)

      case cause(generation, version, targets) do
        nil -> []
        cause -> [{requirement.contact_requirement_id, current.version, cause}]
      end
    end)
  end

  @doc "Pure: the cause a generated requirement is superseded with, or nil."
  @spec cause(map(), ContactRequirementTemplateVersion.t(), MapSet.t()) ::
          :template_versioned | :left_template_target | nil
  def cause(generation, version, targets) do
    cond do
      generation["contact_requirement_template_id"] != version.contact_requirement_template_id ->
        nil

      (generation["contact_requirement_template_version"] || 0) < version.version ->
        :template_versioned

      not MapSet.member?(targets, generation["spacecraft_id"]) ->
        :left_template_target

      true ->
        nil
    end
  end

  defp cancel_unless_taken_up(scope, version, {requirement_id, expected_version, cause}, now) do
    org = version.organization_id
    mission = version.mission_id

    reason = supersession_reason(version, cause)

    Repo.transaction(fn ->
      # Plans first: share-lock every referencing plan and re-check uptake, then the requirement.
      taken_up? =
        org
        |> ContactPlans.requirements_taken_up(mission, [requirement_id], lock: true)
        |> MapSet.member?(requirement_id)

      with false <- taken_up?,
           {:ok, %{lifecycle_state: :active, current_version: ^expected_version}} <-
             ContactRequirements.lock(org, mission, requirement_id),
           {:ok, _canceled} <-
             ContactRequirements.cancel(
               scope,
               mission,
               requirement_id,
               expected_version,
               reason,
               now: now
             ) do
        true
      else
        {:error, error} -> Repo.rollback(error)
        _kept -> false
      end
    end)
    |> case do
      {:ok, superseded?} ->
        superseded?

      # Inside a fleet start's claim, a failed cancel has already poisoned the transaction: fail
      # the start rather than carry on as if it succeeded (review G).
      {:error, error} ->
        if Repo.in_transaction?(), do: Repo.rollback(error)
        Logger.warning("could not supersede requirement #{requirement_id}: #{inspect(error)}")
        false
    end
  end

  defp supersession_reason(version, cause) do
    "#{cause}: superseded by template #{version.contact_requirement_template_id} " <>
      "version #{version.version}"
  end
end
