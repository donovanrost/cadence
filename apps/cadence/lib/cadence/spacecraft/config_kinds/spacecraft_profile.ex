defmodule Cadence.Spacecraft.ConfigKinds.SpacecraftProfile do
  @moduledoc """
  Change-set kind for Spacecraft Profiles (`Cadence.SpacecraftType`).

  Profiles are versioned. Every applied edit writes version v+1, and delete writes a `deleted`
  version. The op option `rollout` decides which pinned spacecraft move to the new version:
  `"all"` (default: every spacecraft pinned to the current version), `"all_versions"` (every
  spacecraft pinned to the profile at any version; C3 "include older versions", expanded when
  the set applies so it can't go stale), `"none"`, or `%{"spacecraft" => [id]}`. Moved spacecraft enter the revision as their own entries.
  Spacecraft whose framing is governed by a configuration review keep their pin and are
  reported as kept.

  The runtime doesn't read profiles directly. Framing reaches it through spacecraft
  configuration activation (see `docs/apogee/domain/profile-routing.md` §4).
  """

  @behaviour Cadence.Platform.ConfigKind

  alias Cadence.Platform.ConfigFields, as: F
  alias Cadence.Platform.ConfigurationSettings
  alias Cadence.Spacecraft.ConfigKinds.Spacecraft, as: SpacecraftKind
  alias Cadence.SpacecraftStore
  alias Cadence.SpacecraftStore.Overrides
  alias Cadence.SpacecraftType
  alias Cadence.SpacecraftType.RoutingRule, as: ProfileRule
  alias Cadence.SpacecraftTypeStore

  @fields ~w(display_name downlink_protocol uplink_protocol packet_protocol frame_parameters
             applications metadata catalog_revision_id composition_id handled_apids
             routing_rules)
  # `fecf` (frame error control field present) is carried by existing profiles and read by the
  # TM frame codec.
  @frame_fields ~w(frame_size secondary_header_length insert_zone_length ocf_length
                   truncated_primary_header fecf)
  @governed_key "spacecraft_configuration_revision_id"
  # The profile paths a framing-governed spacecraft keeps from its configuration review.
  @framing_paths ~w(downlink_protocol uplink_protocol packet_protocol frame_parameters)
  @synthetic_prefix "spacecraft_configuration_profile_"

  @impl true
  def kind, do: "spacecraft_profile"

  @impl true
  def id_prefix, do: "spacecraft_type"

  @impl true
  def load(organization_id, mission_id, ids) do
    for id <- ids,
        {:ok, profile} <- [
          SpacecraftTypeStore.fetch_spacecraft_type(organization_id, mission_id, id)
        ],
        into: %{},
        do: {id, document(profile)}
  end

  @impl true
  def normalize(_action, @synthetic_prefix <> _rest, _document),
    do: {:error, [F.error("", "This profile was generated by a configuration review")]}

  def normalize(:delete, _id, nil), do: {:ok, nil}

  def normalize(_action, _id, %{} = document) do
    document =
      document
      |> Map.put_new("packet_protocol", "space_packet")
      |> Map.put_new("frame_parameters", %{})
      |> Map.put_new("applications", %{})
      |> Map.put_new("metadata", %{})
      |> Map.put_new("catalog_revision_id", nil)

    {rules, rule_errors} =
      case ProfileRule.normalize(Map.get(document, "routing_rules")) do
        {:ok, rules} -> {rules, []}
        {:error, errors} -> {Map.get(document, "routing_rules"), errors}
      end

    document = Map.put(document, "routing_rules", rules)

    errors =
      rule_errors ++
        F.text(document, "catalog_revision_id", 1..255, label: "Catalog revision") ++
        F.text(document, "composition_id", 1..255, label: "Mission composition") ++
        F.only(document, @fields) ++
        F.text(document, "display_name", 1..200, required: true, label: "Name") ++
        F.one_of(document, "downlink_protocol", ~w(tm aos uslp),
          required: true,
          label: "TM transfer frame"
        ) ++
        F.one_of(document, "uplink_protocol", ~w(tc uslp),
          required: true,
          label: "TC transfer frame"
        ) ++
        F.one_of(document, "packet_protocol", ~w(space_packet), label: "Packet protocol") ++
        F.map(document, "applications") ++
        F.map(document, "metadata") ++
        framing(document) ++
        apids_shape(document["handled_apids"], "handled_apids")

    F.result(document, errors)
  end

  def normalize(_action, _id, _document), do: {:error, [F.error("", "Enter the profile details")]}

  @impl true
  def normalize_options(:update, %{"rollout" => rollout} = options) when map_size(options) == 1 do
    case rollout do
      mode when mode in ["all", "all_versions", "none"] ->
        {:ok, options}

      %{"spacecraft" => ids} when is_list(ids) and length(ids) in 1..1_000 ->
        if Enum.all?(ids, &is_binary/1),
          do: {:ok, options},
          else: {:error, [F.error("options.rollout", "List spacecraft ids")]}

      _other ->
        {:error,
         [
           F.error(
             "options.rollout",
             "Roll out to all, all_versions, none, or a list of spacecraft"
           )
         ]}
    end
  end

  def normalize_options(_action, _options),
    do: {:error, [F.error("options", "Only profile edits take a rollout")]}

  @impl true
  def validate(organization_id, mission_id, :delete, entity_id, _previous, nil) do
    case length(SpacecraftStore.list_pinned_to_profile(organization_id, mission_id, entity_id)) do
      0 -> :ok
      count -> {:error, [F.error("", "#{count} spacecraft use this profile")]}
    end
  end

  # DECISIONS #36/#65: a catalog change goes through change sets and produces a runtime
  # generation; it must name a catalog revision that exists.
  def validate(organization_id, mission_id, _action, _entity_id, previous, proposed)
      when is_map(proposed) do
    catalog = proposed["catalog_revision_id"]

    catalog_check =
      if catalog == Map.get(previous || %{}, "catalog_revision_id") or is_nil(catalog),
        do: :ok,
        else: catalog_exists(organization_id, mission_id, catalog, "catalog_revision_id")

    with :ok <- catalog_check,
         do:
           apids_in_catalog(
             organization_id,
             mission_id,
             catalog,
             proposed["handled_apids"],
             "handled_apids"
           )
  end

  def validate(_organization_id, _mission_id, _action, _entity_id, _previous, _proposed), do: :ok

  @impl true
  def write(organization_id, mission_id, :create, id, nil, proposed, _options) do
    with {:ok, profile} <- persist(organization_id, mission_id, id, 1, :active, proposed),
         do: {:ok, document(profile), []}
  end

  def write(organization_id, mission_id, :update, id, _previous, proposed, options) do
    with {:ok, current} <-
           SpacecraftTypeStore.fetch_spacecraft_type(organization_id, mission_id, id),
         {:ok, profile} <-
           persist(organization_id, mission_id, id, current.version + 1, :active, proposed),
         {:ok, moved} <- roll_out(organization_id, mission_id, current, profile, options) do
      {:ok, document(profile), moved}
    end
  end

  def write(organization_id, mission_id, :delete, id, previous, nil, _options) do
    with {:ok, current} <-
           SpacecraftTypeStore.fetch_spacecraft_type(organization_id, mission_id, id),
         {:ok, _profile} <-
           persist(organization_id, mission_id, id, current.version + 1, :deleted, previous),
         do: {:ok, nil, []}
  end

  @impl true
  def effect(organization_id, mission_id, :update, entity_id, previous, proposed, options) do
    case SpacecraftTypeStore.fetch_spacecraft_type(organization_id, mission_id, entity_id) do
      {:ok, current} ->
        changed = changed_paths(previous, proposed)
        rollout_effect(organization_id, mission_id, entity_id, current, options, changed)

      {:error, _missing} ->
        nil
    end
  end

  def effect(_organization_id, _mission_id, _action, _entity_id, _previous, _proposed, _options),
    do: nil

  # The dry run's count and why the rest don't change, each keep with a `code` (fe-setup C3),
  # listing only reasons that bear on the paths the op changes.
  defp rollout_effect(organization_id, mission_id, entity_id, current, options, changed) do
    targets = rollout_targets(organization_id, mission_id, current, rollout(options))
    kept? = kept_fn(organization_id, mission_id)
    {governed, moving} = Enum.split_with(targets, kept?)
    target_ids = MapSet.new(targets, & &1.spacecraft_id)

    {catalog_pinned, moving} =
      if changed == ["catalog_revision_id"],
        do: split_catalog_pinned(organization_id, mission_id, moving),
        else: {[], moving}

    older =
      organization_id
      |> SpacecraftStore.list_pinned_to_profile(mission_id, entity_id)
      |> Enum.reject(&MapSet.member?(target_ids, &1.spacecraft_id))

    governed = if Enum.any?(changed, &(&1 in @framing_paths)), do: governed, else: []

    %{
      changes: length(moving),
      keeps:
        Enum.map(
          governed,
          &keep(&1, "framing is governed by its configuration review", "framing_governed")
        ) ++
          Enum.map(
            catalog_pinned,
            &keep(&1, "its own override sets its catalog", "catalog_override")
          ) ++
          Enum.map(
            older,
            &keep(&1, "stays on v#{&1.spacecraft_type_version}", "older_profile_version")
          )
    }
  end

  # An override at catalog_revision_id keeps the spacecraft's own catalog whatever the profile
  # says (CatalogAuthority), so a catalog-only edit changes nothing for it.
  defp split_catalog_pinned(_organization_id, _mission_id, []), do: {[], []}

  defp split_catalog_pinned(organization_id, mission_id, spacecraft) do
    overrides =
      Overrides.list(organization_id, mission_id, Enum.map(spacecraft, & &1.spacecraft_id))

    Enum.split_with(spacecraft, fn craft ->
      overrides |> Map.get(craft.spacecraft_id, %{}) |> Map.has_key?("catalog_revision_id")
    end)
  end

  defp changed_paths(previous, proposed) when is_map(previous) and is_map(proposed) do
    (Map.keys(previous) ++ Map.keys(proposed))
    |> Enum.uniq()
    |> Enum.reject(&(Map.get(previous, &1) == Map.get(proposed, &1)))
    |> Enum.sort()
  end

  defp changed_paths(_previous, _proposed), do: []

  @impl true
  def summary(:create, nil, proposed), do: "Add profile #{proposed["display_name"]}"
  def summary(:delete, previous, nil), do: "Delete profile #{previous["display_name"]}"
  def summary(:update, previous, _proposed), do: "Edit profile #{previous["display_name"]}"

  @impl true
  def runtime_impact(_action, _previous, _proposed), do: :none

  defp framing(%{"frame_parameters" => %{} = frame} = document) do
    max_frame = if document["downlink_protocol"] in ["tm", "aos"], do: 2048, else: 65_535

    Enum.map(F.only(frame, @frame_fields), &%{&1 | path: "frame_parameters." <> &1.path}) ++
      prefixed(F.integer(frame, "frame_size", 1..max_frame, label: "TM frame length")) ++
      prefixed(F.integer(frame, "secondary_header_length", 0..64, label: "Secondary header")) ++
      prefixed(F.integer(frame, "insert_zone_length", 0..max_frame, label: "Insert zone")) ++
      prefixed(F.one_of(frame, "ocf_length", [0, 4], label: "Operational control field")) ++
      prefixed(
        F.one_of(frame, "truncated_primary_header", [true, false], label: "Truncated header")
      ) ++
      prefixed(F.one_of(frame, "fecf", [true, false], label: "Frame error control field"))
  end

  defp framing(_document), do: [F.error("frame_parameters", "Must be an object")]

  defp prefixed(errors), do: Enum.map(errors, &%{&1 | path: "frame_parameters." <> &1.path})

  defp persist(organization_id, mission_id, id, version, lifecycle, document) do
    profile =
      SpacecraftType.new(%{
        spacecraft_type_id: id,
        organization_id: organization_id,
        mission_id: mission_id,
        version: version,
        lifecycle_state: lifecycle,
        display_name: document["display_name"],
        downlink_protocol: document["downlink_protocol"],
        uplink_protocol: document["uplink_protocol"],
        packet_protocol: document["packet_protocol"],
        frame_parameters: document["frame_parameters"],
        applications: document["applications"],
        metadata: document["metadata"],
        catalog_revision_id: document["catalog_revision_id"],
        composition_id: document["composition_id"],
        handled_apids: document["handled_apids"],
        routing_rules: document["routing_rules"] || []
      })

    SpacecraftTypeStore.persist_spacecraft_type(organization_id, profile)
  end

  # One statement for the whole rollout (director 11-14: moving 499 spacecraft one by one was
  # half the preview's queries).
  defp roll_out(organization_id, mission_id, current, profile, options) do
    targets =
      organization_id
      |> rollout_targets(mission_id, current, rollout(options))
      |> Enum.reject(kept_fn(organization_id, mission_id))

    ids = Enum.map(targets, & &1.spacecraft_id)

    # A target deleted meanwhile refuses the apply, as the per-spacecraft update did
    # (api-ops), rather than raising.
    with {:ok, stored} <-
           SpacecraftStore.set_profile_version(organization_id, mission_id, ids, profile.version),
         true <- map_size(stored) == length(targets) do
      {:ok, Enum.map(targets, &entry(&1, Map.fetch!(stored, &1.spacecraft_id)))}
    else
      false -> {:error, :spacecraft_not_found}
    end
  end

  defp rollout_targets(_organization_id, _mission_id, _current, "none"), do: []

  defp rollout_targets(organization_id, mission_id, current, "all_versions"),
    do:
      SpacecraftStore.list_pinned_to_profile(
        organization_id,
        mission_id,
        current.spacecraft_type_id
      )

  defp rollout_targets(organization_id, mission_id, current, "all") do
    SpacecraftStore.list_pinned_to_profile(
      organization_id,
      mission_id,
      current.spacecraft_type_id,
      version: current.version
    )
  end

  defp rollout_targets(organization_id, mission_id, current, %{"spacecraft" => ids}) do
    SpacecraftStore.list_pinned_to_profile(
      organization_id,
      mission_id,
      current.spacecraft_type_id,
      spacecraft_ids: ids
    )
  end

  defp rollout(options), do: Map.get(options, "rollout", "all")

  defp keep(spacecraft, reason, code),
    do: %{
      spacecraft: %{id: spacecraft.spacecraft_id, name: spacecraft.display_name},
      reason: reason,
      code: code
    }

  # With profile framing generations on, the profile takes framing authority for every moved
  # spacecraft, including ones configured through per-spacecraft review (DECISIONS #33).
  defp kept_fn(organization_id, mission_id) do
    if ConfigurationSettings.profile_framing_generations?(organization_id, mission_id),
      do: fn _spacecraft -> false end,
      else: &governed?/1
  end

  defp governed?(spacecraft), do: is_binary(Map.get(spacecraft.metadata || %{}, @governed_key))

  defp entry(previous, stored) do
    %{
      kind: "spacecraft",
      entity_id: stored.spacecraft_id,
      op: :update,
      previous: SpacecraftKind.document(previous),
      proposed: SpacecraftKind.document(stored)
    }
  end

  defp document(%SpacecraftType{} = profile) do
    %{
      "display_name" => profile.display_name,
      "downlink_protocol" => Atom.to_string(profile.downlink_protocol),
      "uplink_protocol" => Atom.to_string(profile.uplink_protocol),
      "packet_protocol" => Atom.to_string(profile.packet_protocol),
      "frame_parameters" => profile.frame_parameters || %{},
      "applications" => profile.applications || %{},
      "metadata" => profile.metadata || %{},
      "catalog_revision_id" => profile.catalog_revision_id,
      "routing_rules" => profile.routing_rules || []
    }
    # L22: in the document once set, so documents recorded before it compare equal.
    |> then(fn document ->
      if profile.handled_apids,
        do: Map.put(document, "handled_apids", profile.handled_apids),
        else: document
    end)
    # D3 (#544; #108, no legacy-hash shim per domain, #112): in the document once set. A profile
    # change staged before the pin was filled in reads stale at apply and must be re-staged.
    |> then(fn document ->
      if profile.composition_id,
        do: Map.put(document, "composition_id", profile.composition_id),
        else: document
    end)
  end

  @doc false
  # A handled_apids value: nil (all of the catalog's APIDs) or a list of distinct APIDs.
  def apids_shape(nil, _path), do: []

  def apids_shape(apids, path) when is_list(apids) do
    cond do
      apids == [] ->
        [F.error(path, "Choose at least one APID, or all of the catalog's")]

      not Enum.all?(apids, &(is_integer(&1) and &1 in 0..2047)) ->
        [F.error(path, "APIDs are 0 to 2047")]

      length(Enum.uniq(apids)) != length(apids) ->
        [F.error(path, "List each APID once")]

      true ->
        []
    end
  end

  def apids_shape(_apids, path), do: [F.error(path, "List the APIDs, or leave it empty for all")]

  @doc false
  # Every listed APID must be one the catalog defines (422 naming the strays).
  def apids_in_catalog(_organization_id, _mission_id, _catalog, nil, _path), do: :ok
  def apids_in_catalog(_organization_id, _mission_id, nil, _apids, _path), do: :ok

  def apids_in_catalog(organization_id, mission_id, catalog, apids, path) do
    # Configured, so this kind has no compile-time edge to the mission-model context; until the
    # key is configured, the apply's blocking HOLD still refuses strays.
    with reader when reader != nil <- Application.get_env(:cadence, :catalog_apids),
         {:ok, defined} <- reader.apids(organization_id, mission_id, catalog),
         stray when stray != [] <- reader.stray(apids, defined) do
      {:error,
       [
         F.error(
           path,
           "The catalog doesn't define APIDs " <> Enum.map_join(stray, ", ", &Integer.to_string/1)
         )
       ]}
    else
      [] -> :ok
      nil -> :ok
      {:error, _reason} -> :ok
    end
  end

  @doc false
  def catalog_exists(organization_id, mission_id, catalog, path) do
    catalogs = Application.fetch_env!(:cadence, :catalog_revisions)

    case catalogs.fetch_revision(organization_id, mission_id, catalog) do
      {:ok, _revision} -> :ok
      {:error, _not_found} -> {:error, [F.error(path, "That catalog revision doesn't exist")]}
    end
  end
end
