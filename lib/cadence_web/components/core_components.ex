  @doc """
  Renders an avatar with user initials.

  ## Examples

      <.avatar email="john@example.com" />
      <.avatar email="jane@example.com" name="Jane Doe" />
      <.avatar email="user@example.com" size="lg" />
  """
  attr :email, :string, required: true
  attr :name, :string, default: nil
  attr :size, :string, default: "md", values: ~w(sm md lg)
  attr :class, :string, default: nil

  def avatar(assigns) do
    initials =
      if assigns.name do
        assigns.name
        |> String.split()
        |> Enum.take(2)
        |> Enum.map(&String.first/1)
        |> Enum.join()
        |> String.upcase()
      else
        assigns.email
        |> String.split("@")
        |> List.first()
        |> String.first()
        |> String.upcase()
      end

    # Generate consistent color from email hash
    hash = :crypto.hash(:md5, assigns.email) |> :binary.decode_unsigned()
    color_index = rem(hash, 5)

    bg_class =
      case color_index do
        0 -> "bg-primary text-primary-content"
        1 -> "bg-secondary text-secondary-content"
        2 -> "bg-accent text-accent-content"
        3 -> "bg-info text-info-content"
        _ -> "bg-success text-success-content"
      end

    size_class =
      case assigns.size do
        "sm" -> "h-8 w-8 text-xs"
        "md" -> "h-10 w-10 text-sm"
        "lg" -> "h-12 w-12 text-base"
      end

    assigns =
      assigns
      |> assign(:initials, initials)
      |> assign(:bg_class, bg_class)
      |> assign(:size_class, size_class)

    ~H"""
    <div class={[
      "avatar placeholder",
      @class
    ]}>
      <div class={[
        "rounded-full",
        @bg_class,
        @size_class,
        "flex items-center justify-center font-semibold"
      ]}>
        <span>{@initials}</span>
      </div>
    </div>
    """
  end

